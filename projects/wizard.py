def step_form(index, data=None, initial=None):
    form = forms.Form(data=data, initial=initial)
    source = TaskForm()
    for name in STEPS[index][1]:
        form.fields[name] = source.fields[name]
        form.fields[name].help_text = FIELD_GUIDANCE[name]
        form.fields[name].widget.attrs['aria-describedby'] = f'id_{name}_helptext'
    return form
