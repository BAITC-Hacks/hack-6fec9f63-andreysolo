def scope_prompt(fields):
    boundaries = '\n'.join(f'{name}: {description}' for name, description in SCOPES.items())
    return f'''Границы блоков (определяй принадлежность по смыслу, а не по метке field):
{boundaries}
Сейчас разрешены ТОЛЬКО: {', '.join(fields)}.
Упоминание пользователем будущего решения в текущем блоке НЕ разрешает задавать вопросы по другим блокам.
Выбор функций будущего решения относится к need, а не к context; уже указанные функции повторно не выясняй.
Для context уместно: «Опишите, как сотрудники сейчас на глаз оценивают связь рациона с удоями» — если это ещё не объяснено.
Не задавай смешанные вопросы сразу по нескольким блокам. Не повторяй уже сообщённое. Не придумывай вопрос ради количества: если уместных уточнений нет, верни пустой список.
{EDITOR_GUIDANCE}'''
